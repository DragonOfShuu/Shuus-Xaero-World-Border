package dev.dragonofshuu.shuusxaeroworldborder.overlays.types;

/** A single point in GUI pixels, the companion to {@link ScreenRect}. */
public final class ScreenPoint {
    public final float x;
    public final float y;

    public ScreenPoint(float x, float y) {
        this.x = x;
        this.y = y;
    }
}
